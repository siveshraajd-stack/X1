/** @jest-environment node */

// In-memory stand-in for the three tables the approval flow touches
const db = { leaves: [], notifications: [], users: [] };

jest.mock('@/lib/db', () => ({
    prisma: {
        leaveRequest: {
            findMany: async ({ where }) =>
                db.leaves.filter(
                    (l) => l.userId === where.userId && l.status === 'APPROVED' && where.type.in.includes(l.type)
                ),
            findUnique: async ({ where }) => {
                const l = db.leaves.find((x) => x.id === where.id);
                if (!l) return null;
                return { ...l, user: db.users.find((u) => u.id === l.userId) };
            },
            updateMany: async ({ where, data }) => {
                const l = db.leaves.find((x) => x.id === where.id && x.status === where.status && x.autoGenerated === where.autoGenerated);
                if (!l) return { count: 0 };
                Object.assign(l, data);
                return { count: 1 };
            },
        },
        user: { findMany: async ({ where }) => db.users.filter((u) => u.companyId === where.companyId && u.role === where.role) },
        notification: {
            create: async ({ data }) => db.notifications.push(data),
            createMany: async ({ data }) => db.notifications.push(...data),
        },
    },
}));
const mockSend = jest.fn(async () => ({ sent: true }));
jest.mock('@/lib/mailer', () => ({
    appBaseUrl: () => 'http://localhost',
    escapeHtml: (v) => String(v ?? ''),
    sendMail: (...args) => mockSend(...args),
}));

const { decideLeave, decisionStageFor, getLeaveBalance, assertWithinQuota } = require('@/lib/leave');

const emp = { id: 'e1', name: 'Emp', email: 'emp@kaspl.net', companyId: 'c1', role: 'EMPLOYEE' };
const mgr = { id: 'm1', name: 'Mgr', email: 'manager@kaspl.net', companyId: 'c1', role: 'MANAGER' };
const hr = { id: 'h1', name: 'HR', email: 'hr@kaspl.net', companyId: 'c1', role: 'ADMIN' };

function seed(overrides = {}) {
    db.users = [emp, mgr, hr];
    db.notifications = [];
    mockSend.mockClear();
    db.leaves = [
        {
            id: 'l1',
            userId: 'e1',
            managerId: 'm1',
            type: 'CASUAL',
            startDate: new Date('2026-12-01T00:00:00+05:30'),
            endDate: new Date('2026-12-02T00:00:00+05:30'),
            days: 2,
            status: 'PENDING',
            autoGenerated: false,
            ...overrides,
        },
    ];
}
const toEmployee = () => db.notifications.filter((n) => n.userId === 'e1');
const toHr = () => db.notifications.filter((n) => n.userId === 'h1');

describe('leave approval: employee -> manager -> HR (no manager above the approver)', () => {
    beforeEach(() => seed());

    test('manager approves: goes to HR, employee is told nothing yet', async () => {
        const r = await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr });
        expect(r.final).toBe(false);
        expect(db.leaves[0].status).toBe('MANAGER_APPROVED');
        expect(db.leaves[0].managerDecidedAt).toBeInstanceOf(Date);
        expect(toHr()).toHaveLength(1);
        expect(toEmployee()).toHaveLength(0);
        expect(mockSend).not.toHaveBeenCalled();
    });

    test('manager + HR approve: leave accepted, employee notified', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr });
        const r = await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: hr });
        expect(r.final).toBe(true);
        expect(db.leaves[0].status).toBe('APPROVED');
        expect(toEmployee()).toHaveLength(1);
        expect(toEmployee()[0].title).toBe('Leave accepted');
        expect(mockSend).toHaveBeenCalledTimes(1);
    });

    test('manager rejects: employee told "not accepted", HR gets nothing', async () => {
        const r = await decideLeave({ leaveId: 'l1', decision: 'REJECTED', comment: 'busy', decider: mgr });
        expect(r.final).toBe(true);
        expect(db.leaves[0].status).toBe('REJECTED');
        expect(db.leaves[0].rejectedBy).toBe('MANAGER');
        expect(toHr()).toHaveLength(0);
        expect(toEmployee()[0].title).toBe('Leave not accepted');
    });

    test('HR rejects after manager approved: employee told "not accepted"', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr });
        await decideLeave({ leaveId: 'l1', decision: 'REJECTED', comment: 'policy', decider: hr });
        expect(db.leaves[0].status).toBe('REJECTED');
        expect(db.leaves[0].rejectedBy).toBe('HR');
        expect(db.leaves[0].hrComment).toBe('policy');
        expect(toEmployee()[0].title).toBe('Leave not accepted');
    });

    test('a decided request cannot be decided again', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'REJECTED', comment: 'no cover', decider: mgr });
        await expect(decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: hr })).rejects.toMatchObject({ status: 409 });
    });

    test('rejecting without a reason is refused', async () => {
        await expect(decideLeave({ leaveId: 'l1', decision: 'REJECTED', comment: '  ', decider: mgr })).rejects.toMatchObject({ status: 400 });
        expect(db.leaves[0].status).not.toBe('REJECTED');
    });

    test('a manager cannot give the HR decision', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr });
        await expect(decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr })).rejects.toBeTruthy();
        expect(db.leaves[0].status).toBe('MANAGER_APPROVED');
    });

    test('HR who is the assigned manager decides in one step', async () => {
        seed({ managerId: 'h1' });
        const r = await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: hr });
        expect(r.final).toBe(true);
        expect(db.leaves[0].status).toBe('APPROVED');
        expect(toEmployee()).toHaveLength(1);
    });
});

describe('leave approval: employee -> team lead -> manager -> HR', () => {
    const tl = { id: 't1', name: 'Team Lead', email: 'tl@kaspl.net', companyId: 'c1', role: 'MANAGER' };
    const chain = (overrides = {}) => {
        seed({ managerId: 't1', upperManagerId: 'm1', ...overrides });
        db.users = [emp, mgr, hr, tl];
    };
    const toManager = () => db.notifications.filter((n) => n.userId === 'm1');

    beforeEach(() => chain());

    test('team lead approves: goes to the manager (with Accept / Deny popup), not to HR, employee told nothing', async () => {
        const r = await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: tl });
        expect(r.final).toBe(false);
        expect(db.leaves[0].status).toBe('TEAM_LEAD_APPROVED');
        expect(db.leaves[0].teamLeadDecidedAt).toBeInstanceOf(Date);
        expect(toManager()).toHaveLength(1);
        expect(toManager()[0]).toMatchObject({ type: 'LEAVE_ACTION', leaveId: 'l1' });
        expect(toHr()).toHaveLength(0);
        expect(toEmployee()).toHaveLength(0);
        expect(mockSend).not.toHaveBeenCalled();
    });

    test('manager approves: goes to HR with an Accept / Deny popup', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: tl });
        const r = await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr });
        expect(r.final).toBe(false);
        expect(db.leaves[0].status).toBe('MANAGER_APPROVED');
        expect(toHr()).toHaveLength(1);
        expect(toHr()[0]).toMatchObject({ type: 'LEAVE_ACTION', leaveId: 'l1' });
        expect(toEmployee()).toHaveLength(0);
    });

    test('team lead + manager + HR approve: employee is told it was accepted', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: tl });
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr });
        const r = await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: hr });
        expect(r.final).toBe(true);
        expect(db.leaves[0].status).toBe('APPROVED');
        expect(toEmployee()).toHaveLength(1);
        expect(toEmployee()[0].title).toBe('Leave accepted');
        expect(mockSend).toHaveBeenCalledTimes(1);
    });

    test('team lead denies: employee is told who denied, manager and HR get nothing', async () => {
        const r = await decideLeave({ leaveId: 'l1', decision: 'REJECTED', comment: 'busy', decider: tl });
        expect(r.final).toBe(true);
        expect(db.leaves[0].status).toBe('REJECTED');
        expect(db.leaves[0].rejectedBy).toBe('TEAM_LEAD');
        expect(db.leaves[0].teamLeadComment).toBe('busy');
        expect(toManager()).toHaveLength(0);
        expect(toHr()).toHaveLength(0);
        expect(toEmployee()[0].title).toBe('Leave not accepted');
        expect(toEmployee()[0].message).toContain('Team Lead');
    });

    test('manager denies after the team lead approved: employee is told, HR gets nothing', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: tl });
        await decideLeave({ leaveId: 'l1', decision: 'REJECTED', comment: 'no cover', decider: mgr });
        expect(db.leaves[0].status).toBe('REJECTED');
        expect(db.leaves[0].rejectedBy).toBe('MANAGER');
        expect(db.leaves[0].adminComment).toBe('no cover');
        expect(toHr()).toHaveLength(0);
        expect(toEmployee()).toHaveLength(1);
        expect(toEmployee()[0].message).toContain('Manager');
    });

    test('HR denies at the last step: employee is told', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: tl });
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr });
        await decideLeave({ leaveId: 'l1', decision: 'REJECTED', comment: 'policy', decider: hr });
        expect(db.leaves[0].status).toBe('REJECTED');
        expect(db.leaves[0].rejectedBy).toBe('HR');
        expect(toEmployee()[0].message).toContain('HR');
    });

    test('steps cannot be skipped: a team lead cannot give the manager decision, HR cannot skip the manager', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: tl });
        // still TEAM_LEAD_APPROVED: only the manager (or HR when no manager exists) may decide
        expect(decisionStageFor(db.leaves[0], tl)).toBeNull();
        expect(decisionStageFor(db.leaves[0], hr)).toBeNull();
        expect(decisionStageFor(db.leaves[0], mgr)).toBe('MANAGER');
    });

    test('who may decide at each step', () => {
        const base = { userId: 'e1', managerId: 't1', upperManagerId: 'm1', autoGenerated: false };
        expect(decisionStageFor({ ...base, status: 'PENDING' }, tl)).toBe('TEAM_LEAD');
        expect(decisionStageFor({ ...base, status: 'PENDING' }, mgr)).toBeNull();
        expect(decisionStageFor({ ...base, status: 'TEAM_LEAD_APPROVED' }, mgr)).toBe('MANAGER');
        expect(decisionStageFor({ ...base, status: 'TEAM_LEAD_APPROVED' }, tl)).toBeNull();
        expect(decisionStageFor({ ...base, status: 'MANAGER_APPROVED' }, hr)).toBe('HR');
        expect(decisionStageFor({ ...base, status: 'MANAGER_APPROVED' }, mgr)).toBeNull();
        // manager step with no manager left: HR can step in
        expect(decisionStageFor({ ...base, upperManagerId: null, status: 'TEAM_LEAD_APPROVED' }, hr)).toBe('MANAGER');
    });

    test('balance only drops after the final HR approval', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: tl });
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr });
        expect((await getLeaveBalance('e1', 2026)).casual.remaining).toBe(8);
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: hr });
        expect((await getLeaveBalance('e1', 2026)).casual).toMatchObject({ used: 2, remaining: 6 });
    });
});

describe('decisionStageFor', () => {
    const base = { userId: 'e1', managerId: 'm1', autoGenerated: false };

    test('step 1 is only for the assigned manager', () => {
        expect(decisionStageFor({ ...base, status: 'PENDING' }, mgr)).toBe('TEAM_LEAD');
        expect(decisionStageFor({ ...base, status: 'PENDING' }, { ...mgr, id: 'other' })).toBeNull();
        expect(decisionStageFor({ ...base, status: 'PENDING' }, hr)).toBeNull(); // HR waits for the manager
    });
    test('HR may decide step 1 only when no manager is assigned', () => {
        expect(decisionStageFor({ ...base, managerId: null, status: 'PENDING' }, hr)).toBe('TEAM_LEAD');
    });
    test('step 2 is HR only', () => {
        expect(decisionStageFor({ ...base, status: 'MANAGER_APPROVED' }, hr)).toBe('HR');
        expect(decisionStageFor({ ...base, status: 'MANAGER_APPROVED' }, mgr)).toBeNull();
    });
    test('nobody decides own, auto-generated or final requests', () => {
        expect(decisionStageFor({ ...base, userId: 'm1', status: 'PENDING' }, mgr)).toBeNull();
        expect(decisionStageFor({ ...base, autoGenerated: true, status: 'PENDING' }, mgr)).toBeNull();
        expect(decisionStageFor({ ...base, status: 'APPROVED' }, hr)).toBeNull();
        expect(decisionStageFor({ ...base, status: 'REJECTED' }, hr)).toBeNull();
    });
});

describe('yearly quota: Sick 8 and Casual 8', () => {
    const approved = (type, days, id) => ({
        id,
        userId: 'e1',
        type,
        days,
        status: 'APPROVED',
        autoGenerated: false,
        startDate: new Date('2026-03-02T00:00:00+05:30'),
        endDate: new Date('2026-03-03T00:00:00+05:30'),
    });

    beforeEach(() => seed());

    test('fresh employee has 8 sick and 8 casual', async () => {
        const b = await getLeaveBalance('e1', 2026);
        expect(b.sick).toMatchObject({ allowance: 8, used: 0, remaining: 8 });
        expect(b.casual).toMatchObject({ allowance: 8, used: 0, remaining: 8 });
        expect(b).toMatchObject({ allowance: 16, used: 0, remaining: 16 });
    });

    test('balance only drops when the request is finally accepted', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr }); // manager step only
        expect((await getLeaveBalance('e1', 2026)).casual.remaining).toBe(8);
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: hr }); // final
        const b = await getLeaveBalance('e1', 2026);
        expect(b.casual).toMatchObject({ used: 2, remaining: 6 });
        expect(b.sick.remaining).toBe(8); // sick is untouched
    });

    test('a rejected request never reduces the balance', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'REJECTED', decider: mgr });
        expect((await getLeaveBalance('e1', 2026)).casual.remaining).toBe(8);
    });

    test('sick and casual are separate pools', async () => {
        db.leaves.push(approved('SICK', 8, 's1'));
        const b = await getLeaveBalance('e1', 2026);
        expect(b.sick.remaining).toBe(0);
        expect(b.casual.remaining).toBe(8);
    });

    test('final approval is blocked when the category does not have enough days left', async () => {
        db.leaves.push(approved('CASUAL', 7, 'c7')); // 1 casual day left, request needs 2
        await expect(decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: hr, comment: 'x' })).rejects.toMatchObject({ status: 400 });
        expect(db.leaves.find((l) => l.id === 'l1').status).toBe('PENDING');
    });

    test('assertWithinQuota counts days already reserved by open requests', () => {
        expect(() => assertWithinQuota({ type: 'SICK', days: 3, remaining: 8, reserved: 5 })).not.toThrow();
        expect(() => assertWithinQuota({ type: 'SICK', days: 4, remaining: 8, reserved: 5 })).toThrow(/Not enough Sick leave/);
        expect(() => assertWithinQuota({ type: 'LOP', days: 99, remaining: 0 })).not.toThrow(); // unlimited categories
    });
});
