/** @jest-environment node */

// In-memory stand-in for Prisma: leave approval, OD claims and attendance
const db = { users: [], leaves: [], claims: [], attendance: [], holidays: [], overrides: [], notifications: [], seq: { n: 0 } };
const sameTime = (a, b) => new Date(a).getTime() === new Date(b).getTime();

jest.mock('@/lib/db', () => ({
    prisma: {
        user: {
            findUnique: async ({ where }) => db.users.find((u) => u.id === where.id) || null,
            findMany: async ({ where }) =>
                db.users.filter((u) => u.companyId === where.companyId && u.role === where.role && (!where.id || u.id !== where.id.not)),
        },
        holiday: {
            findMany: async () => db.holidays,
            findUnique: async ({ where }) => db.holidays.find((h) => sameTime(h.date, where.companyId_date.date)) || null,
        },
        attendanceOverride: {
            findMany: async () => db.overrides,
            findUnique: async ({ where }) => db.overrides.find((o) => sameTime(o.date, where.companyId_date.date)) || null,
        },
        attendance: {
            findFirst: async ({ where }) => db.attendance.filter((a) => a.userId === where.userId).sort((a, b) => a.date - b.date)[0] || null,
            findUnique: async ({ where }) =>
                db.attendance.find((a) => a.userId === where.userId_date.userId && sameTime(a.date, where.userId_date.date)) || null,
            findMany: async ({ where }) =>
                db.attendance.filter((a) => a.userId === where.userId && a.date >= where.date.gte && a.date < where.date.lt),
            upsert: async ({ where, create, update }) => {
                const row = db.attendance.find((a) => a.userId === where.userId_date.userId && sameTime(a.date, where.userId_date.date));
                if (row) return Object.assign(row, update);
                const created = { id: `a${++db.seq.n}`, ...create };
                db.attendance.push(created);
                return created;
            },
            count: async ({ where }) =>
                db.attendance.filter((a) => a.userId === where.userId && a.status === where.status && a.date >= where.date.gte && a.date < where.date.lt).length,
        },
        leaveRequest: {
            findFirst: async ({ where }) =>
                db.leaves.find((l) => l.userId === where.userId && l.status === 'APPROVED' && l.startDate <= where.startDate.lte && l.endDate >= where.endDate.gte) || null,
            findUnique: async ({ where }) => {
                const l = db.leaves.find((x) => (where.id ? x.id === where.id : x.lateKey === where.lateKey));
                return l ? { ...l, user: db.users.find((u) => u.id === l.userId) } : null;
            },
            findMany: async ({ where }) => {
                if (where.autoGenerated) {
                    return db.leaves.filter((l) => l.userId === where.userId && l.autoGenerated && String(l.lateKey).startsWith(where.lateKey.startsWith));
                }
                if (where.type) {
                    // yearly balance query
                    return db.leaves.filter((l) => l.userId === where.userId && l.status === 'APPROVED' && where.type.in.includes(l.type));
                }
                return db.leaves.filter((l) => l.userId === where.userId && l.status === where.status && l.startDate < where.startDate.lt && l.endDate >= where.endDate.gte);
            },
            updateMany: async ({ where, data }) => {
                const l = db.leaves.find((x) => x.id === where.id && x.status === where.status);
                if (!l) return { count: 0 };
                Object.assign(l, data);
                return { count: 1 };
            },
            delete: async ({ where }) => {
                db.leaves = db.leaves.filter((l) => l.id !== where.id);
            },
        },
        expenseClaim: {
            findFirst: async ({ where }) =>
                db.claims.find((c) => c.userId === where.userId && c.status === 'APPROVED' && c.fromDate <= where.fromDate.lte && c.toDate >= where.toDate.gte) || null,
            updateMany: async ({ where, data }) => {
                const c = db.claims.find((x) => x.id === where.id && x.status === where.status);
                if (!c) return { count: 0 };
                Object.assign(c, data);
                return { count: 1 };
            },
            findUnique: async ({ where }) => {
                const c = db.claims.find((x) => x.id === where.id);
                return c ? { ...c, user: db.users.find((u) => u.id === c.userId) } : null;
            },
        },
        notification: {
            create: async ({ data }) => db.notifications.push(data),
            createMany: async ({ data }) => db.notifications.push(...data),
        },
    },
}));
const mockSend = jest.fn(async () => ({ sent: true }));
jest.mock('@/lib/mailer', () => ({
    appBaseUrl: () => 'http://localhost',
    escapeHtml: (v) => String(v ?? ''),
    sendMail: (...args) => mockSend(...args),
}));
jest.mock('@/lib/whatsapp', () => ({ sendWhatsApp: async () => ({ sent: true }) }));

const { dayStart, dayKey } = require('@/lib/dates');
const { decideExpense } = require('@/lib/expense');
const { decideLeave } = require('@/lib/leave');
const { markAttendance } = require('@/lib/attendance-core');

const emp = { id: 'e1', name: 'Sam Carter', email: 'sam@x.net', phone: null, companyId: 'c1', role: 'EMPLOYEE', createdAt: new Date('2026-01-01T00:00:00+05:30') };
const mgr = { id: 'm1', name: 'Ravi Kumar', email: 'ravi@x.net', companyId: 'c1', role: 'MANAGER' };
const hr = { id: 'h1', name: 'Meena Iyer', email: 'meena@x.net', companyId: 'c1', role: 'ADMIN' };
const d = (key) => dayStart(key);
const toEmp = () => db.notifications.filter((n) => n.userId === 'e1');

function reset() {
    db.users = [emp, mgr, hr];
    db.leaves = [];
    db.claims = [];
    db.attendance = [];
    db.holidays = [];
    db.overrides = [];
    db.notifications = [];
    mockSend.mockClear();
}

describe('approved OD claim marks the employee as OD', () => {
    beforeEach(() => {
        reset();
        // Mon 7 Dec 2026 .. Sun 13 Dec 2026
        db.claims = [{ id: 'c1', userId: 'e1', managerId: 'm1', category: 'FOOD', amount: 500, projectName: 'Atlas', status: 'MANAGER_APPROVED', fromDate: d('2026-12-07'), toDate: d('2026-12-13') }];
    });

    test('Present / Late / Absent days become OD, empty days get OD, weekend is skipped, punches are kept', async () => {
        const punch = new Date('2026-12-09T09:40:00+05:30');
        db.attendance = [
            { id: 'a1', userId: 'e1', date: d('2026-12-08'), status: 'PRESENT' },
            { id: 'a2', userId: 'e1', date: d('2026-12-09'), status: 'LATE', checkIn: punch },
            { id: 'a3', userId: 'e1', date: d('2026-12-10'), status: 'ABSENT' },
        ];
        const out = await decideExpense({ claimId: 'c1', decision: 'APPROVED', comment: 'ok', decider: hr });
        expect(out.final).toBe(true);
        const byKey = Object.fromEntries(db.attendance.map((a) => [dayKey(a.date), a]));
        for (const key of ['2026-12-07', '2026-12-08', '2026-12-09', '2026-12-10', '2026-12-11']) expect(byKey[key].status).toBe('OD');
        expect(byKey['2026-12-12']).toBeUndefined(); // Saturday
        expect(byKey['2026-12-13']).toBeUndefined(); // Sunday
        expect(byKey['2026-12-09'].checkIn).toBe(punch); // biometric time untouched
        expect(db.claims[0]).toMatchObject({ status: 'APPROVED', hrDecidedByName: 'Meena Iyer' });
        expect(toEmp()[0].message).toContain('approved by Meena Iyer (HR)');
        expect(toEmp()[0].message).toContain('marked On Duty (OD) for 5 days');
    });

    test('holidays and approved-leave days are not touched; running twice changes nothing more', async () => {
        db.holidays = [{ date: d('2026-12-08'), name: 'Fest' }];
        db.leaves = [{ id: 'l1', userId: 'e1', status: 'APPROVED', type: 'CASUAL', startDate: d('2026-12-09'), endDate: d('2026-12-09'), days: 1 }];
        await decideExpense({ claimId: 'c1', decision: 'APPROVED', decider: hr });
        const keys = db.attendance.map((a) => dayKey(a.date)).sort();
        expect(keys).toEqual(['2026-12-07', '2026-12-10', '2026-12-11']);
        const { markOdDays } = require('@/lib/attendance-core');
        await markOdDays({ userId: 'e1', fromKey: '2026-12-07', toKey: '2026-12-13' });
        expect(db.attendance).toHaveLength(3);
    });

    test('a LATE day turned into OD gives back the automatic late deduction', async () => {
        db.attendance = ['01', '02', '03', '04', '05'].map((day, i) => ({ id: `L${i}`, userId: 'e1', date: d(`2026-12-${day}`), status: 'LATE' }));
        db.leaves = [{ id: 'auto1', userId: 'e1', autoGenerated: true, lateKey: 'e1:2026-12:1', status: 'APPROVED', type: 'CASUAL', days: 1, startDate: d('2026-12-05'), endDate: d('2026-12-05') }];
        db.claims[0].fromDate = d('2026-12-02');
        db.claims[0].toDate = d('2026-12-02');
        await decideExpense({ claimId: 'c1', decision: 'APPROVED', decider: hr });
        expect(db.attendance.find((a) => dayKey(a.date) === '2026-12-02').status).toBe('OD');
        expect(db.leaves.find((l) => l.id === 'auto1')).toBeUndefined();
        expect(toEmp().some((n) => n.title === 'Late deduction reversed')).toBe(true);
    });

    test('a rejected claim marks nothing', async () => {
        await decideExpense({ claimId: 'c1', decision: 'REJECTED', comment: 'no', decider: hr });
        expect(db.attendance).toHaveLength(0);
        expect(toEmp()[0].message).toContain('rejected by Meena Iyer (HR)');
    });
});

describe('an approved OD day cannot be changed back to Present / Late', () => {
    const now = new Date('2026-12-08T09:30:00+05:30'); // Tuesday
    beforeEach(() => {
        reset();
        db.attendance = [{ id: 'a1', userId: 'e1', date: d('2026-12-08'), status: 'OD' }];
    });

    test('blocked while the OD claim is approved', async () => {
        db.claims = [{ id: 'c1', userId: 'e1', status: 'APPROVED', fromDate: d('2026-12-07'), toDate: d('2026-12-09') }];
        await expect(markAttendance({ user: emp, status: 'PRESENT', now })).rejects.toThrow('approved On Duty');
        expect(db.attendance[0].status).toBe('OD');
    });

    test('an OD the employee marked for themselves (no approved claim) can still be changed today', async () => {
        // before 9:00 AM so the late rule does not turn it into LATE
        const out = await markAttendance({ user: emp, status: 'WFH', now: new Date('2026-12-08T08:30:00+05:30') });
        expect(out.status).toBe('WFH');
    });
});

describe('notifications use real names, not "the manager" / "HR"', () => {
    beforeEach(() => {
        reset();
        db.leaves = [{ id: 'l1', userId: 'e1', managerId: 'm1', upperManagerId: null, type: 'CASUAL', startDate: d('2030-03-04'), endDate: d('2030-03-05'), days: 2, status: 'PENDING', autoGenerated: false }];
    });

    test('manager approves: HR is told who approved, the manager name is saved on the request', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr });
        const toHr = db.notifications.filter((n) => n.userId === 'h1');
        expect(toHr[0].title).toContain('Ravi Kumar (Manager)');
        expect(toHr[0].message).toContain('approved by Ravi Kumar (Manager)');
        expect(db.leaves[0].managerDecidedByName).toBe('Ravi Kumar');
    });

    test('HR decides: the employee gets HR\'s name in the notification and the email', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: mgr });
        await decideLeave({ leaveId: 'l1', decision: 'APPROVED', decider: hr });
        expect(toEmp()[0].message).toContain('accepted by Meena Iyer (HR)');
        expect(db.leaves[0].hrDecidedByName).toBe('Meena Iyer');
        const mail = mockSend.mock.calls.map(([m]) => m).find((m) => m.to === 'sam@x.net');
        expect(mail.subject).toContain('Meena Iyer (HR)');
        expect(mail.text).toContain('Meena Iyer (HR)');
    });

    test('rejection by the manager names the manager', async () => {
        await decideLeave({ leaveId: 'l1', decision: 'REJECTED', comment: 'busy week', decider: mgr });
        expect(toEmp()[0].message).toContain('not accepted by Ravi Kumar (Manager)');
        expect(db.leaves[0]).toMatchObject({ status: 'REJECTED', rejectedBy: 'MANAGER', managerDecidedByName: 'Ravi Kumar' });
    });
});
