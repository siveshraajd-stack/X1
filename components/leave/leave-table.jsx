'use client';

import { useState } from 'react';
import { LEAVE_TYPES } from '@/lib/constants';

const STATUS_CLASS = {
    PENDING: 'bg-primary-100 text-primary-700',
    TEAM_LEAD_APPROVED: 'bg-sky-100 text-sky-700',
    MANAGER_APPROVED: 'bg-amber-100 text-amber-700',
    APPROVED: 'bg-secondary-100 text-secondary-700',
    REJECTED: 'bg-red-100 text-red-700',
};
const DOT_CLASS = {
    PENDING: 'bg-primary-500',
    TEAM_LEAD_APPROVED: 'bg-sky-500',
    MANAGER_APPROVED: 'bg-amber-500',
    APPROVED: 'bg-secondary-500',
    REJECTED: 'bg-red-500',
};

// What the person sees for each state of the team lead -> manager -> HR approval flow
const STATUS_LABEL = {
    PENDING: 'Pending (team lead)',
    TEAM_LEAD_APPROVED: 'Team lead approved',
    MANAGER_APPROVED: 'Manager approved',
    APPROVED: 'Approved',
    REJECTED: 'Rejected',
};

const nameOr = (name, role) => (name ? `${name} (${role})` : role);
const hrText = (hrNames) => (hrNames && hrNames.length ? hrNames.slice(0, 3).join(', ') + (hrNames.length > 3 ? ` +${hrNames.length - 3} more` : '') + ' (HR)' : 'HR');

// Status text with the real names: who it is waiting for, who approved, who rejected
function statusText(leave, hrNames) {
    const firstRole = leave.upperManager ? 'Team lead' : 'Manager';
    const firstName = leave.teamLeadDecidedByName || leave.managerDecidedByName || leave.manager?.name;
    if (leave.status === 'PENDING') return `Pending · ${nameOr(leave.manager?.name, firstRole)}`;
    if (leave.status === 'TEAM_LEAD_APPROVED') {
        return `Approved by ${nameOr(leave.teamLeadDecidedByName || leave.manager?.name, 'Team lead')} · waiting for ${nameOr(leave.upperManager?.name, 'Manager')}`;
    }
    if (leave.status === 'MANAGER_APPROVED') {
        const by = leave.upperManager ? leave.managerDecidedByName || leave.upperManager?.name : firstName;
        return `Approved by ${nameOr(by, 'Manager')} · waiting for ${hrText(hrNames)}`;
    }
    if (leave.status === 'APPROVED') {
        if (leave.autoGenerated) return 'Approved (automatic)';
        return leave.hrDecidedByName ? `Approved by ${leave.hrDecidedByName} (HR)` : 'Approved';
    }
    if (leave.status === 'REJECTED') {
        const by =
            leave.rejectedBy === 'HR'
                ? nameOr(leave.hrDecidedByName, 'HR')
                : leave.rejectedBy === 'TEAM_LEAD'
                  ? nameOr(leave.teamLeadDecidedByName, 'Team lead')
                  : leave.rejectedBy === 'MANAGER'
                    ? nameOr(leave.managerDecidedByName, 'Manager')
                    : null;
        return by ? `Rejected by ${by}` : 'Rejected';
    }
    return STATUS_LABEL[leave.status] || leave.status;
}

const fmt = (d) => String(d).slice(0, 10).split('-').reverse().join('-');
// Dates are stored as midnight IST; show the IST calendar day
const istDay = (d) => new Date(new Date(d).getTime() + 330 * 60 * 1000).toISOString().slice(0, 10);

const WAITING = ['PENDING', 'TEAM_LEAD_APPROVED', 'MANAGER_APPROVED'];

export function LeaveTable({ leaves, showEmployee = false, showManager = false, onDecide, onCancel, onFollowUp, hrNames = [], emptyText = 'No requests' }) {
    const [busyId, setBusyId] = useState(null);

    const decide = async (leave, status) => {
        let comment;
        if (status === 'REJECTED') {
            const answer = window.prompt('Reason for denying (required):');
            if (answer === null) return; // cancelled: do not reject
            if (!answer.trim()) {
                window.alert('A reason is required to deny a request.');
                return;
            }
            comment = answer.trim().slice(0, 300);
        }
        setBusyId(leave.id);
        try {
            await onDecide(leave.id, status, comment);
        } finally {
            setBusyId(null);
        }
    };

    // Employee's own requests: cancel, or remind the person who has not accepted yet
    const own = async (leave, fn, ask) => {
        if (ask && !window.confirm(ask)) return;
        setBusyId(leave.id);
        try {
            await fn(leave.id);
        } finally {
            setBusyId(null);
        }
    };

    if (leaves.length === 0) {
        return (
            <div className="k-card p-12 text-center">
                <div className="mx-auto w-14 h-14 rounded-2xl bg-primary-50 flex items-center justify-center text-primary-500 text-2xl">∅</div>
                <p className="mt-4 text-sm font-semibold text-[var(--ink-soft)]">{emptyText}</p>
            </div>
        );
    }

    return (
        <div className="space-y-3">
            {leaves.map((leave) => (
                <article key={leave.id} className="k-card k-card-hover p-5 flex flex-wrap items-center gap-x-6 gap-y-3">
                    <div className="flex items-center gap-4 min-w-[210px] flex-1">
                        <div className="w-12 h-12 rounded-2xl bg-gradient-to-br from-primary-400 to-primary-700 text-white flex items-center justify-center font-bold text-lg shrink-0">
                            {(showEmployee ? leave.user?.name : LEAVE_TYPES[leave.type] || leave.type || '?')?.charAt(0)?.toUpperCase()}
                        </div>
                        <div className="min-w-0">
                            {showEmployee && (
                                <p className="font-bold text-sm truncate">
                                    {leave.user?.name} <span className="text-[11px] text-[var(--ink-soft)] font-semibold">{leave.user?.employeeId}</span>
                                </p>
                            )}
                            <p className={showEmployee ? 'text-xs font-semibold text-primary-700' : 'font-bold text-sm'}>
                                {LEAVE_TYPES[leave.type] || leave.type}
                                {leave.autoGenerated && <span className="ml-2 k-chip bg-primary-50 text-primary-600 !py-0.5">auto</span>}
                            </p>
                            <p className="text-xs text-[var(--ink-soft)] mt-0.5">
                                {istDay(leave.startDate) === istDay(leave.endDate)
                                    ? fmt(istDay(leave.startDate))
                                    : `${fmt(istDay(leave.startDate))} → ${fmt(istDay(leave.endDate))}`}
                            </p>
                        </div>
                    </div>

                    <div className="text-center px-2">
                        <p className="text-2xl font-bold leading-none">{leave.days ?? '-'}</p>
                        <p className="k-label mt-1">{leave.days === 1 ? 'day' : 'days'}</p>
                    </div>

                    <div className="flex-[2] min-w-[200px] max-w-md">
                        <p className="k-label mb-1">Reason</p>
                        <p className="text-sm break-words">{leave.reason || '-'}</p>
                        {leave.type === 'COMPENSATE' && leave.compensateForDate && (
                            <p className="text-[11px] text-[var(--ink-soft)] mt-1">
                                Worked on <b>{fmt(leave.compensateForDate)}</b> → taking <b>{fmt(istDay(leave.startDate))}{istDay(leave.endDate) !== istDay(leave.startDate) ? ` to ${fmt(istDay(leave.endDate))}` : ''}</b> off
                            </p>
                        )}
                        {leave.type === 'OD' && (leave.siteLocation || leave.projectName) && (
                            <p className="text-[11px] text-[var(--ink-soft)] mt-1">
                                {leave.siteLocation ? <>Site: <b>{leave.siteLocation}</b></> : null}
                                {leave.siteLocation && leave.projectName ? ' · ' : ''}
                                {leave.projectName ? <>Project: <b>{leave.projectName}</b></> : null}
                            </p>
                        )}
                        {showManager && (
                            <p className="text-[11px] text-[var(--ink-soft)] mt-1">
                                {leave.upperManager ? 'Team lead' : 'Manager'}: <b>{leave.manager?.name || '-'}</b>
                                {leave.upperManager && (
                                    <>
                                        {' · '}Manager: <b>{leave.upperManager.name}</b>
                                    </>
                                )}
                            </p>
                        )}
                    </div>

                    <div className="flex flex-col items-end gap-2 ml-auto">
                        <span className={`k-chip ${STATUS_CLASS[leave.status] || 'bg-gray-100 text-gray-700'}`}>
                            <span className={`w-1.5 h-1.5 rounded-full ${DOT_CLASS[leave.status] || 'bg-gray-400'}`} />
                            {statusText(leave, hrNames)}
                        </span>
                        {(onCancel || onFollowUp) && WAITING.includes(leave.status) && !leave.autoGenerated && (
                            <div className="flex gap-2">
                                {onFollowUp && (
                                    <button
                                        disabled={busyId === leave.id}
                                        onClick={() => own(leave, onFollowUp)}
                                        className="px-4 py-1.5 rounded-full bg-primary-50 hover:bg-primary-100 text-primary-700 text-xs font-bold disabled:opacity-50"
                                    >
                                        Follow up
                                    </button>
                                )}
                                {onCancel && (
                                    <button
                                        disabled={busyId === leave.id}
                                        onClick={() => own(leave, onCancel, 'Cancel this request?')}
                                        className="px-4 py-1.5 rounded-full bg-red-50 hover:bg-red-100 text-red-600 text-xs font-bold disabled:opacity-50"
                                    >
                                        Cancel request
                                    </button>
                                )}
                            </div>
                        )}
                        {onDecide &&
                            (leave.canDecide ? (
                                <div className="flex gap-2">
                                    <button
                                        disabled={busyId === leave.id}
                                        onClick={() => decide(leave, 'APPROVED')}
                                        className="px-4 py-1.5 rounded-full bg-secondary-600 hover:bg-secondary-700 text-white text-xs font-bold disabled:opacity-50"
                                    >
                                        Approve
                                    </button>
                                    <button
                                        disabled={busyId === leave.id}
                                        onClick={() => decide(leave, 'REJECTED')}
                                        className="px-4 py-1.5 rounded-full bg-red-50 hover:bg-red-100 text-red-600 text-xs font-bold disabled:opacity-50"
                                    >
                                        Reject
                                    </button>
                                </div>
                            ) : (
                                <span className="text-[11px] text-[var(--ink-soft)] font-semibold">
                                    {leave.status === 'MANAGER_APPROVED'
                                        ? `Awaiting ${hrText(hrNames)}`
                                        : leave.status === 'TEAM_LEAD_APPROVED'
                                          ? `Awaiting ${nameOr(leave.upperManager?.name, 'Manager')}`
                                          : ''}
                                </span>
                            ))}
                    </div>
                </article>
            ))}
        </div>
    );
}
