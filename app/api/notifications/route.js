import { NextResponse } from 'next/server';
import { getServerSession } from 'next-auth';
import { authOptions } from '@/app/api/auth/[...nextauth]/route';
import { prisma } from '@/lib/db';
import NotificationService from '@/lib/notifications';
import { decisionStageFor } from '@/lib/leave';

const notificationService = new NotificationService();

export async function GET(request) {
    try {
        const session = await getServerSession(authOptions);

        if (!session) {
            return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
        }

        const { searchParams } = new URL(request.url);
        const page = parseInt(searchParams.get('page')) || 1;
        const limit = parseInt(searchParams.get('limit')) || 20;
        const unreadOnly = searchParams.get('unreadOnly') === 'true';

        const skip = (page - 1) * limit;

        const where = {
            userId: session.user.id,
            ...(unreadOnly && { isRead: false })
        };

        const [notifications, total, unreadCount] = await Promise.all([
            prisma.notification.findMany({
                where,
                orderBy: { createdAt: 'desc' },
                skip,
                take: limit
            }),
            prisma.notification.count({ where }),
            prisma.notification.count({
                where: {
                    userId: session.user.id,
                    isRead: false
                }
            })
        ]);

        // For leave notifications: can THIS user still accept / deny the request right now?
        // (false once somebody has decided it, so the popup buttons disappear)
        const leaveIds = [...new Set(notifications.map((n) => n.leaveId).filter(Boolean))];
        const leaveById = {};
        if (leaveIds.length) {
            const leaves = await prisma.leaveRequest.findMany({
                where: { id: { in: leaveIds } },
                select: {
                    id: true,
                    status: true,
                    userId: true,
                    managerId: true,
                    upperManagerId: true,
                    autoGenerated: true,
                    user: { select: { name: true } },
                },
            });
            for (const l of leaves) leaveById[l.id] = l;
        }
        const enriched = notifications.map((n) => {
            const leave = n.leaveId ? leaveById[n.leaveId] : null;
            return {
                ...n,
                leaveStatus: leave ? leave.status : null,
                leaveCanDecide: leave ? decisionStageFor(leave, session.user) !== null : false,
            };
        });

        return NextResponse.json({
            notifications: enriched,
            total,
            page,
            totalPages: Math.ceil(total / limit),
            unreadCount
        });
    } catch (error) {
        console.error('Fetch notifications error:', error);
        return NextResponse.json(
            { error: 'An error occurred while fetching notifications' },
            { status: 500 }
        );
    }
}

export async function POST(request) {
    try {
        const session = await getServerSession(authOptions);

        if (!session || session.user.role !== 'ADMIN') {
            return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
        }

        const body = await request.json();
        const { userId, type, title, message, priority = 'NORMAL', category = 'SYSTEM', actionUrl, actionText } = body;

        if (!userId || !type || !title || !message) {
            return NextResponse.json({ error: 'Missing required fields' }, { status: 400 });
        }

        const notification = await notificationService.createNotification({
            userId,
            type,
            title,
            message,
            priority,
            category,
            actionUrl,
            actionText
        });

        return NextResponse.json(notification);
    } catch (error) {
        console.error('Error creating notification:', error);
        return NextResponse.json({ error: 'Internal server error' }, { status: 500 });
    }
}

export async function PATCH(request) {
    try {
        const session = await getServerSession(authOptions);

        if (!session) {
            return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
        }

        const body = await request.json();
        const id = body.id || body.notificationId;

        if (id) {
            // Only the owner can mark a notification as read
            await prisma.notification.updateMany({
                where: { id, userId: session.user.id },
                data: { isRead: true },
            });
        } else if (body.markAll) {
            // Mark all as read
            await prisma.notification.updateMany({
                where: { userId: session.user.id, isRead: false },
                data: { isRead: true },
            });
        }

        return NextResponse.json({ message: 'Notifications updated' });
    } catch (error) {
        console.error('Update notifications error:', error);
        return NextResponse.json(
            { error: 'An error occurred while updating notifications' },
            { status: 500 }
        );
    }
}

export async function DELETE(request) {
    try {
        const session = await getServerSession(authOptions);

        if (!session) {
            return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
        }

        const params = new URL(request.url).searchParams;
        // Delete every message of the logged in user (works in every dashboard)
        if (params.get('all') === 'true') {
            const result = await prisma.notification.deleteMany({ where: { userId: session.user.id } });
            return NextResponse.json({ message: 'All notifications deleted', deleted: result.count });
        }

        const id = params.get('notificationId');
        if (!id) {
            return NextResponse.json({ error: 'notificationId is required' }, { status: 400 });
        }

        // Only the owner can delete a notification
        await prisma.notification.deleteMany({ where: { id, userId: session.user.id } });
        return NextResponse.json({ message: 'Notification deleted' });
    } catch (error) {
        console.error('Delete notification error:', error);
        return NextResponse.json(
            { error: 'An error occurred while deleting the notification' },
            { status: 500 }
        );
    }
}
