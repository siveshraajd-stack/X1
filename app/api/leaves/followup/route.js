import { NextResponse } from 'next/server';
import { prisma } from '@/lib/db';
import { requireUser } from '@/lib/access';
import { AppError, errorResponseParts } from '@/lib/errors';
import { WAITING_LEAVE_STATUSES, isNonLeaveType, leaveTypeLabel, requestWord } from '@/lib/constants';
import { dayKey } from '@/lib/dates';
import { currentApproverIds } from '@/lib/leave';

const FOLLOW_UP_GAP_MS = 60 * 60 * 1000; // one reminder per request per hour

// POST /api/leaves/followup { id }
// The employee reminds the person who has not accepted their request yet (team lead, manager or HR).
export async function POST(request) {
    try {
        const user = await requireUser();
        const { id } = await request.json().catch(() => ({}));
        if (!id) throw new AppError('Request id is required', 400);

        const leave = await prisma.leaveRequest.findUnique({ where: { id } });
        if (!leave || leave.userId !== user.id) throw new AppError('Leave request not found', 404);
        if (leave.autoGenerated || !WAITING_LEAVE_STATUSES.includes(leave.status)) {
            throw new AppError('This request is already decided, so there is nobody to follow up with', 409);
        }

        const approverIds = await currentApproverIds(leave, user.companyId);
        if (!approverIds.length) throw new AppError('Nobody is assigned to decide this request yet', 400);

        const recent = await prisma.notification.findFirst({
            where: {
                leaveId: id,
                userId: { in: approverIds },
                title: { startsWith: 'Follow-up' },
                createdAt: { gte: new Date(Date.now() - FOLLOW_UP_GAP_MS) },
            },
            select: { id: true },
        });
        if (recent) throw new AppError('You already sent a follow-up for this request in the last hour. Please wait before sending another.', 429);

        const start = dayKey(leave.startDate);
        const end = dayKey(leave.endDate);
        const range = start === end ? start : `${start} to ${end}`;
        const what = isNonLeaveType(leave.type) ? leaveTypeLabel(leave.type) : `${leaveTypeLabel(leave.type)} leave`;
        const approvers = await prisma.user.findMany({
            where: { id: { in: approverIds } },
            select: { id: true, role: true },
        });
        await prisma.notification.createMany({
            data: approvers.map((a) => ({
                userId: a.id,
                type: 'LEAVE_ACTION',
                title: `Follow-up: ${requestWord(leave.type).toLowerCase()} request from ${user.name}`,
                message: `${user.name} is waiting for your decision on their ${what} request (${range}). Please accept or deny.`,
                senderName: user.name,
                priority: 'HIGH',
                leaveId: leave.id,
                actionUrl: a.role === 'ADMIN' ? '/admin/time-off' : '/dashboard/team',
                actionText: 'Review request',
            })),
        });
        return NextResponse.json({ message: 'Follow-up sent. They have been notified again.' });
    } catch (error) {
        const [body, status] = errorResponseParts(error, 'Failed to send the follow-up');
        return NextResponse.json(body, { status });
    }
}
